# MAIN
# Start the application
def main() -> int:
    parser = argparse.ArgumentParser()

    parser.add_argument(
        "--limit",
        type=int,
        default=0,
        help="Processa somente N mapas. 0 = todos.",
    )

    parser.add_argument(
        "--force",
        action="store_true",
        help="Reconverte os JSONs mesmo quando já há cache.",
    )

    parser.add_argument(
        "--timeout",
        type=int,
        default=300,
    )

    args = parser.parse_args()

    validate_config()

    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    maps_cache = CACHE_DIR / "maps"
    classes_cache = CACHE_DIR / "classes"

    maps_cache.mkdir(parents=True, exist_ok=True)
    classes_cache.mkdir(parents=True, exist_ok=True)

    candidates = load_material_candidate_maps()
    total_available = len(candidates)

    if args.limit > 0:
        candidates = candidates[:args.limit]

    print()
    print("Code Vein 2 Renewable Material Scanner v2")
    print("=" * 60)
    print(f"Candidate maps available: {total_available}")
    print(f"Candidate maps processed: {len(candidates)}")
    print("Os JSONs existentes serão reutilizados.")
    print()

    instance_rows: list[dict[str, Any]] = []
    failures: list[dict[str, str]] = []

    # ========================================================
    # STAGE 1 - MAP -> ACTOR -> CLASS VIA IMPORTS
    # ========================================================

    for number, row in enumerate(candidates, start=1):
        filename = (row.get("file") or "").strip()

        source = GENERATED_DIR / filename
        cache = maps_cache / f"{source.stem}.json"

        print(f"[MAP {number}/{len(candidates)}] {filename}")

        if not source.is_file():
            failures.append({
                "stage": "map_source",
                "file": filename,
                "error": "generated map not found",
            })
            print("    MISSING MAP")
            continue

        if args.force or not cache.exists():
            print("    converting...")
            ok, error = run_tojson(source, cache, args.timeout)

            if not ok:
                failures.append({
                    "stage": "map_tojson",
                    "file": filename,
                    "error": error,
                })
                print(f"    ERROR: {error}")
                continue
        else:
            print("    cache")

        try:
            document = load_json(cache)
        except Exception as exc:
            failures.append({
                "stage": "map_json",
                "file": filename,
                "error": repr(exc),
            })
            print("    JSON ERROR")
            continue

        if not isinstance(document, dict):
            failures.append({
                "stage": "map_json",
                "file": filename,
                "error": "unexpected JSON root type",
            })
            continue

        found = 0

        for export_index, export in iter_exports(document):
            actor_name = export_name(export, export_index)

            class_name, package_path = resolve_export_class(
                document,
                export,
            )

            if not looks_like_resource_class(class_name, package_path):
                continue

            instance_rows.append({
                "map_file": filename,
                "export_index": export_index,
                "actor_name": actor_name,
                "resource_class_package": package_path,
                "resource_class_name": resource_class_name(
                    package_path,
                    class_name,
                ),
                "unique_save_id": extract_guid(export),
                "item_path": "",
                "count": "",
                "bNotification": "",
                "class_asset_status": "",
            })

            found += 1

        print(f"    material actors: {found}")

        if found == 0:
            failures.append({
                "stage": "instance_detect",
                "file": filename,
                "error": "no material actor resolved through ClassIndex/Imports",
            })

    # ========================================================
    # STAGE 2 - RESOURCE CLASS -> REWARD
    # ========================================================

    unique_packages = sorted({
        row["resource_class_package"]
        for row in instance_rows
        if row["resource_class_package"]
    })

    print()
    print("=" * 60)
    print(f"Unique resource classes: {len(unique_packages)}")
    print("=" * 60)

    class_info: dict[str, dict[str, Any]] = {}
    missing_classes: list[str] = []

    for index, package in enumerate(unique_packages, start=1):
        print(f"[CLASS {index}/{len(unique_packages)}] {package}")

        source = package_to_uasset(package)

        safe_cache_name = re.sub(
            r"[^A-Za-z0-9_.-]+",
            "_",
            package.strip("/"),
        )

        cache = classes_cache / f"{safe_cache_name}.json"

        if not source.is_file():
            class_info[package] = {
                "status": "MISSING_CLASS_ASSET",
                "item_path": "",
                "count": "",
                "bNotification": "",
            }
            missing_classes.append(package)
            print("    MISSING CLASS ASSET")
            continue

        if args.force or not cache.exists():
            print("    converting...")
            ok, error = run_tojson(source, cache, args.timeout)

            if not ok:
                class_info[package] = {
                    "status": "CLASS_TOJSON_FAILED",
                    "item_path": "",
                    "count": "",
                    "bNotification": "",
                }
                failures.append({
                    "stage": "class_tojson",
                    "file": str(source),
                    "error": error,
                })
                print(f"    ERROR: {error}")
                continue
        else:
            print("    cache")

        try:
            class_document = load_json(cache)
            item_path, count, notification = extract_class_reward(
                class_document
            )
        except Exception as exc:
            class_info[package] = {
                "status": "CLASS_JSON_FAILED",
                "item_path": "",
                "count": "",
                "bNotification": "",
            }
            failures.append({
                "stage": "class_json",
                "file": str(source),
                "error": repr(exc),
            })
            print("    JSON ERROR")
            continue

        status = "RESOLVED" if item_path else "REWARD_NOT_FOUND"

        class_info[package] = {
            "status": status,
            "item_path": item_path,
            "count": count,
            "bNotification": notification,
        }

        if item_path:
            print(f"    reward: {item_path}")
        else:
            print("    reward not found")

    # Merge class reward data into each placed instance.
    for row in instance_rows:
        info = class_info.get(row["resource_class_package"], {})

        row["item_path"] = info.get("item_path", "")
        row["count"] = info.get("count", "")
        row["bNotification"] = info.get("bNotification", "")
        row["class_asset_status"] = info.get("status", "UNKNOWN")

    # ========================================================
    # OUTPUT
    # ========================================================

    catalog_path = OUTPUT_DIR / "materials_catalog.csv"
    manifest_path = OUTPUT_DIR / "materials_catalog_manifest.json"
    summary_path = OUTPUT_DIR / "materials_catalog_summary.txt"
    missing_path = OUTPUT_DIR / "materials_missing_classes.txt"
    failures_path = OUTPUT_DIR / "materials_catalog_failures.csv"

    fields = [
        "map_file",
        "export_index",
        "actor_name",
        "resource_class_package",
        "resource_class_name",
        "unique_save_id",
        "item_path",
        "count",
        "bNotification",
        "class_asset_status",
    ]

    with catalog_path.open(
        "w",
        encoding="utf-8-sig",
        newline="",
    ) as f:
        writer = csv.DictWriter(f, fieldnames=fields)
        writer.writeheader()
        writer.writerows(instance_rows)

    with failures_path.open(
        "w",
        encoding="utf-8-sig",
        newline="",
    ) as f:
        writer = csv.DictWriter(
            f,
            fieldnames=["stage", "file", "error"],
        )
        writer.writeheader()
        writer.writerows(failures)

    missing_path.write_text(
        "\n".join(missing_classes) + ("\n" if missing_classes else ""),
        encoding="utf-8",
    )

    resolved_instances = sum(
        1
        for row in instance_rows
        if row["class_asset_status"] == "RESOLVED"
    )

    unique_items = {
        row["item_path"]
        for row in instance_rows
        if row["item_path"]
    }

    manifest = {
        "schema_version": 1,
        "script_revision": SCRIPT_REVISION,
        "pickup_types_sha256": sha256_file(PICKUP_TYPES_CSV),
        "candidate_maps_available": total_available,
        "candidate_maps_processed": len(candidates),
        "material_instances": len(instance_rows),
        "unique_resource_classes": len(unique_packages),
        "resolved_instances": resolved_instances,
        "unique_resolved_items": len(unique_items),
        "missing_class_assets": len(missing_classes),
        "failures": len(failures),
    }

    manifest_path.write_text(
        json.dumps(manifest, indent=2, ensure_ascii=False),
        encoding="utf-8",
    )

    summary = (
        "Code Vein 2 - Renewable Material Catalog\n"
        "=========================================\n\n"
        f"Candidate maps available: {total_available}\n"
        f"Candidate maps processed: {len(candidates)}\n"
        f"Material instances found: {len(instance_rows)}\n"
        f"Unique resource classes: {len(unique_packages)}\n"
        f"Resolved instances/rewards: {resolved_instances}\n"
        f"Unique resolved reward items: {len(unique_items)}\n"
        f"Missing resource-class assets: {len(missing_classes)}\n"
        f"Failures: {len(failures)}\n"
    )

    summary_path.write_text(summary, encoding="utf-8")

    print()
    print("=" * 60)
    print("DONE")
    print("=" * 60)
    print(summary)
    print(f"Catalog : {catalog_path}")
    print(f"Missing : {missing_path}")
    print(f"Failures: {failures_path}")

    if missing_classes:
        print()
        print(
            "Agora o scanner conseguiu identificar as classes, "
            "mas algumas não estão extraídas localmente."
        )
        print(
            "Extraia as classes listadas em materials_missing_classes.txt "
            "e rode novamente."
        )

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
