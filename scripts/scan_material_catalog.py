# SOURCE CSV
# Load material candidate maps
def load_material_candidate_maps() -> list[dict[str, str]]:
    with PICKUP_TYPES_CSV.open(
        "r",
        encoding="utf-8-sig",
        newline="",
    ) as f:
        rows = list(csv.DictReader(f))

    return [
        row
        for row in rows
        if (row.get("RENEWABLE_MATERIAL") or "").strip()
    ]


