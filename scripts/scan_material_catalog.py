# UNREAL PACKAGE INDEX RESOLUTION
# Get import
def get_import(document: dict[str, Any], package_index: int) -> dict[str, Any] | None:
    """
    Unreal PackageIndex:
      0    = null
      > 0  = Exports[index - 1]
      < 0  = Imports[-index - 1]

    Example:
      ClassIndex = -5 -> Imports[4]
    """
    if package_index >= 0:
        return None

    imports = document.get("Imports", [])
    py_index = (-package_index) - 1

    if not isinstance(imports, list):
        return None

    if py_index < 0 or py_index >= len(imports):
        return None

    value = imports[py_index]
    return value if isinstance(value, dict) else None


# Resolve import package
def resolve_import_package(
    document: dict[str, Any],
    import_package_index: int,
) -> str:
    """
    Resolve an Import to its owning package.

    For the confirmed material example:
      actor ClassIndex = -5
      Imports[4] = BP_it23_001_A_1_C
      Imports[4].OuterIndex = -38
      Imports[37].ObjectName =
        /Game/Environment/Item/it23/it23_001/BP_it23_001_A_1
    """
    current_index = import_package_index
    visited: set[int] = set()

    while current_index < 0 and current_index not in visited:
        visited.add(current_index)

        imp = get_import(document, current_index)
        if not imp:
            return ""

        object_name = imp.get("ObjectName")
        class_name = imp.get("ClassName")

        # Package imports hold the full /Game/... path directly.
        if (
            isinstance(object_name, str)
            and object_name.startswith("/Game/")
            and class_name == "Package"
        ):
            return object_name

        # Some imports expose a usable game path in ClassPackage.
        class_package = imp.get("ClassPackage")
        if (
            isinstance(class_package, str)
            and class_package.startswith("/Game/")
            and RESOURCE_PREFIX in class_package
        ):
            return class_package

        outer = imp.get("OuterIndex")
        if not isinstance(outer, int) or outer == 0:
            return ""

        current_index = outer

    return ""


# Resolve export class
def resolve_export_class(
    document: dict[str, Any],
    export: dict[str, Any],
) -> tuple[str, str]:
    """
    Returns:
      (class_object_name, class_package_path)
    """
    class_index = export.get("ClassIndex")

    if not isinstance(class_index, int) or class_index >= 0:
        return "", ""

    class_import = get_import(document, class_index)
    if not class_import:
        return "", ""

    class_object_name = str(class_import.get("ObjectName") or "")
    package_path = resolve_import_package(document, class_index)

    return class_object_name, package_path


