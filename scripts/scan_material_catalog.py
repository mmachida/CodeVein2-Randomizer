# MATERIAL INSTANCE DETECTION
# Check for a renewable resource class
def looks_like_resource_class(class_name: str, package_path: str) -> bool:
    if not class_name.startswith("BP_it"):
        return False

    if not class_name.endswith("_C"):
        return False

    return package_path.startswith(RESOURCE_PREFIX)


# Resolve resource class name
def resource_class_name(package_path: str, imported_class_name: str) -> str:
    if imported_class_name:
        return imported_class_name

    if package_path:
        return package_path.rsplit("/", 1)[-1] + "_C"

    return ""


# Build package to UAsset
def package_to_uasset(package: str) -> Path:
    relative = package

    if relative.startswith("/Game/"):
        relative = relative[len("/Game/"):]

    return CONTENT_DIR / (relative + ".uasset")


