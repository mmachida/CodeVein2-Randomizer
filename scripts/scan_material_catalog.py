# REWARD DETECTION FROM RESOURCE CLASS
# Find Article paths in the export
def find_article_paths(obj: Any) -> list[str]:
    paths: list[str] = []

    for text in all_strings(obj):
        if ARTICLE_PREFIX not in text:
            continue

        match = re.search(
            r"(/Game/Blueprint/Article/[A-Za-z0-9_./-]+)",
            text,
        )

        if not match:
            continue

        path = match.group(1).rstrip("\"' ,}]")

        if path not in paths:
            paths.append(path)

    return paths


# Check for a Blueprint CDO
def is_cdo(export: dict[str, Any], name: str) -> bool:
    if name.startswith("Default__"):
        return True

    return "RF_ClassDefaultObject" in " ".join(all_strings(export))


# Extract class reward
def extract_class_reward(document: Any) -> tuple[str, Any, Any]:
    exports = list(iter_exports(document))

    # Prefer CDO first.
    exports.sort(
        key=lambda pair: (
            0 if is_cdo(pair[1], export_name(pair[1], pair[0])) else 1
        )
    )

    for _, export in exports:
        paths = find_article_paths(export)

        if not paths:
            continue

        item_path = next(
            (path for path in paths if "/Article/Item/" in path),
            paths[0],
        )

        count = scalar(find_named_property_value(export, "Count"))
        notification = scalar(
            find_named_property_value(export, "bNotification")
        )

        return (
            item_path,
            "" if count is None else count,
            "" if notification is None else notification,
        )

    return "", "", ""


