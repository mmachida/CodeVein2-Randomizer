# GENERIC HELPERS
# Calculate a file SHA-256 hash
def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


# Validate config
def validate_config() -> None:
    errors: list[str] = []

    if not GENERATED_DIR.is_dir():
        errors.append(f"GENERATED_DIR não encontrado:\n  {GENERATED_DIR}")

    if not PICKUP_TYPES_CSV.is_file():
        errors.append(f"pickup_types.csv não encontrado:\n  {PICKUP_TYPES_CSV}")

    if not UASSETGUI_EXE.is_file():
        errors.append(
            f"UAssetGUI.exe não encontrado:\n  {UASSETGUI_EXE}\n"
            "Edite UASSETGUI_EXE no começo do script."
        )

    if errors:
        print("\nCONFIG ERROR\n" + "=" * 60)
        for error in errors:
            print(error)
            print()
        raise SystemExit(2)


# Convert the result to JSON
def run_tojson(source: Path, destination: Path, timeout: int) -> tuple[bool, str]:
    destination.parent.mkdir(parents=True, exist_ok=True)

    command = [
        str(UASSETGUI_EXE),
        "tojson",
        str(source),
        str(destination),
        ENGINE_VERSION,
        MAPPING_NAME,
    ]

    try:
        process = subprocess.run(
            command,
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            timeout=timeout,
        )
    except subprocess.TimeoutExpired:
        return False, f"TIMEOUT ({timeout}s)"
    except Exception as exc:
        return False, repr(exc)

    if process.returncode != 0:
        text = (process.stderr or process.stdout or "").strip()
        return False, f"exit={process.returncode}: {text[:1500]}"

    if not destination.exists():
        text = (process.stderr or process.stdout or "").strip()
        return False, "UAssetGUI terminou sem criar JSON: " + text[:1500]

    return True, ""


# Load JSON
def load_json(path: Path) -> Any:
    with path.open("r", encoding="utf-8-sig") as f:
        return json.load(f)


# Read iter exports
def iter_exports(document: Any) -> Iterable[tuple[int, dict[str, Any]]]:
    exports = document.get("Exports", []) if isinstance(document, dict) else []

    if isinstance(exports, list):
        for package_index, export in enumerate(exports, start=1):
            if isinstance(export, dict):
                # package_index is Unreal's positive 1-based export index.
                yield package_index, export


# Read the export name
def export_name(export: dict[str, Any], package_index: int) -> str:
    value = export.get("ObjectName")
    if isinstance(value, str) and value:
        return value
    return f"Export_{package_index}"


# Read strings from exports
def all_strings(obj: Any) -> Iterable[str]:
    if isinstance(obj, str):
        yield obj
    elif isinstance(obj, dict):
        for value in obj.values():
            yield from all_strings(value)
    elif isinstance(obj, list):
        for value in obj:
            yield from all_strings(value)


# Find named property value
def find_named_property_value(obj: Any, wanted_name: str) -> Any:
    wanted = wanted_name.lower()

    # Read walk
    def walk(value: Any) -> Any:
        if isinstance(value, dict):
            for key, child in value.items():
                if str(key).lower() == wanted:
                    return child

            name = value.get("Name")
            if isinstance(name, str) and name.lower() == wanted:
                for key in ("Value", "GenericValue", "StructValue"):
                    if key in value:
                        return value[key]
                return value

            for child in value.values():
                result = walk(child)
                if result is not None:
                    return result

        elif isinstance(value, list):
            for child in value:
                result = walk(child)
                if result is not None:
                    return result

        return None

    return walk(obj)


# Read a scalar property
def scalar(value: Any) -> Any:
    if isinstance(value, (str, int, float, bool)) or value is None:
        return value

    if isinstance(value, dict):
        for key in ("Value", "GenericValue", "AssetPathName", "Text"):
            if key in value:
                return scalar(value[key])

    return value


# Read the export GUID
def extract_guid(obj: Any) -> str:
    value = find_named_property_value(obj, "UniqueSaveID")
    if value is None:
        return ""

    text = value if isinstance(value, str) else json.dumps(value, ensure_ascii=False)

    match = re.search(
        r"[{(]?([0-9A-Fa-f]{8})[- ]?([0-9A-Fa-f]{4})[- ]?"
        r"([0-9A-Fa-f]{4})[- ]?([0-9A-Fa-f]{4})[- ]?"
        r"([0-9A-Fa-f]{12})[)}]?",
        text,
    )

    if match:
        return "-".join(match.groups()).upper()

    return text[:250]


